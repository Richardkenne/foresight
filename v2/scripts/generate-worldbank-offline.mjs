const SOURCE = 'World Bank Open Data';
const SOURCE_URL = 'https://data.worldbank.org/indicator/';

let totalFiles = 0;
let totalDp = 0;

for (const [iso3, countryData] of Object.entries(WORLDBANK_DATA)) {
  const { country_name, ...indicators } = countryData;

  const dataPointsObj = {};
  for (const [key, val] of Object.entries(indicators)) {
    dataPointsObj[key] = {
      value: val.value,
      source: `${SOURCE} — ${key} (${val.year})`,
      sourceUrl: `${SOURCE_URL}${key.toUpperCase().replace(/_/g, '.')}?locations=${iso3}`,
      year: val.year,
      ...(val.note ? { note: val.note } : {}),
    };
  }

  const dp = Object.keys(dataPointsObj).length;
  const out = {
    _meta: {
      country: iso3,
      country_name,
      created: '2026-05-24',
      source: SOURCE,
      sourceUrl: `https://data.worldbank.org/country/${iso3.toLowerCase()}`,
      categories: ['demographics', 'education', 'labor', 'health', 'digital', 'governance', 'environment'],
    },
    dataPoints: dp,
    ...dataPointsObj,
  };

  const outPath = join(DATA_DIR, `worldbank-${iso3.toLowerCase()}.json`);
  writeFileSync(outPath, JSON.stringify(out, null, 2));
  console.log(`  ${iso3}: ${dp} dp → ${outPath.split('/').pop()}`);
  totalFiles++;
  totalDp += dp;
}

console.log(`\nDone. Files: ${totalFiles} | Total dataPoints: ${totalDp}`);
